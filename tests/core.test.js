const assert=require('node:assert/strict');
const C=require('../assets/core.js');
const t=s=>+new Date('2026-11-24T'+s);
const study={id:'a',type:'study',start:t('17:00:00'),end:t('17:35:00')};
const rest={id:'b',type:'rest',start:t('17:35:00'),end:t('17:45:00')};
assert.equal(C.overlaps(study,rest),false,'Adjacent records are allowed');
assert.ok(C.conflict({...study,end:t('17:40:00')},[study,rest]),'Cross-category overlap blocked');
assert.equal(C.conflict(study,[study,rest]),null,'Self excluded');
assert.ok(C.conflict({id:'x',start:t('16:00:00'),end:t('18:00:00')},[study]));
assert.ok(C.conflict({id:'x',start:t('17:10:00'),end:t('17:20:00')},[study]));
assert.equal(C.totals([study,rest],'2026-11-24'),35*60000);
assert.equal(C.totals([study,rest],'2026-11-24','rest'),10*60000);
const midnight={id:'c',type:'study',start:+new Date('2026-11-24T23:50:00'),end:+new Date('2026-11-25T00:20:00')};
assert.equal(C.totals([midnight],'2026-11-24'),10*60000);
assert.equal(C.totals([midnight],'2026-11-25'),20*60000);
assert.equal(C.onDay([midnight],'2026-11-25').length,1);
assert.ok(C.validate({...study,end:study.start},[],null,t('19:00:00')));
assert.ok(C.validate({...study,end:NaN},[],null,t('19:00:00')));
assert.equal(C.validate(study,[study,rest],null,t('19:00:00')),'');
assert.ok(C.validate({...study,end:t('18:15:00')},[study],{type:'rest',start:t('18:00:00')},t('19:00:00')));
assert.equal(C.clock(3723000),'01:02:03');
assert.equal(C.duration(35*60000),'35분');
assert.equal(C.duration(1000),'1초');
assert.equal(C.duration(7200000),'2시간');
console.log('18 assertions passed: overlap, adjacency, totals, midnight, validation, duration.');
